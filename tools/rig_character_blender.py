def import_and_merge_character_mesh(glb_path: pathlib.Path, target_height: float, yaw_deg: float) -> bpy.types.Object:
    bpy.ops.import_scene.gltf(filepath=str(glb_path.resolve()))
    meshes = [o for o in bpy.data.objects if o.type == "MESH"]
    if not meshes:
        raise RuntimeError(f"No meshes found in {glb_path}")

    bpy.ops.object.select_all(action="DESELECT")
    for m in meshes:
        m.select_set(True)
    bpy.context.view_layer.objects.active = meshes[0]
    if len(meshes) > 1:
        bpy.ops.object.join()
    obj = bpy.context.view_layer.objects.active
    obj.name = "CharacterBody"

    # Remove any leftover empties / armatures from raw glb
    for other in list(bpy.data.objects):
        if other != obj:
            bpy.data.objects.remove(other, do_unlink=True)

    # Apply existing transforms + optional yaw correction
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    if abs(yaw_deg) > 1e-3:
        obj.rotation_euler.z = math.radians(yaw_deg)
        bpy.ops.object.transform_apply(location=False, rotation=True, scale=False)

    # Compute world bounds and normalize: centered X/Y, feet at Z=0, height = target_height
    verts = [v.co for v in obj.data.vertices]
    xs = [v.x for v in verts]
    ys = [v.y for v in verts]
    zs = [v.z for v in verts]
    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)
    min_z, max_z = min(zs), max(zs)
    h = max(max_z - min_z, 1e-4)
    scale = target_height / h
    cx = 0.5 * (min_x + max_x)
    cy = 0.5 * (min_y + max_y)

    for v in obj.data.vertices:
        v.co.x = (v.co.x - cx) * scale
        v.co.y = (v.co.y - cy) * scale
        v.co.z = (v.co.z - min_z) * scale
    obj.data.update()

    # Weld close doubles & recalculate consistent outward normals for clean heat-diffusion skinning
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    bpy.ops.mesh.remove_doubles(threshold=0.0008)
    bpy.ops.mesh.normals_make_consistent(inside=False)
    bpy.ops.object.mode_set(mode="OBJECT")

    # Smooth shading for crisp curved 3D normal maps
    for poly in obj.data.polygons:
        poly.use_smooth = True

    print(
        f"[rig] normalized mesh: verts={len(obj.data.vertices)} faces={len(obj.data.polygons)} "
        f"height={target_height:.3f}",
        flush=True,
    )
    return obj


def median(vals: list[float], default: float) -> float:
    if not vals:
        return default
    s = sorted(vals)
    return s[len(s) // 2]


def measure_character_landmarks(obj: bpy.types.Object, preset: str) -> dict[str, Any]:
    """Measures anatomical joint positions directly from the normalized A-pose mesh."""
    verts = [v.co for v in obj.data.vertices]
    H = max(v.z for v in verts)
    max_abs_x = max(abs(v.x) for v in verts)

    # Bulky mech presets (Vulcanus, Slag Enforcer) have wider shoulders/hips and slightly lower head.
    is_bulky = preset in ("vulcanus", "enforcer")

    # 1. Measure leg centerline cleanly near boots/shins (z in [0.05*H, 0.17*H]) where coat tails don't reach.
    leg_l_xs = [v.x for v in verts if 0.05 * H <= v.z <= 0.17 * H and v.x > 0.015 * H]
    leg_r_xs = [-v.x for v in verts if 0.05 * H <= v.z <= 0.17 * H and v.x < -0.015 * H]
    leg_xs = leg_l_xs + leg_r_xs
    x_leg = median(leg_xs, 0.12 * H if is_bulky else 0.095 * H)
    x_leg = max(0.07 * H, min(0.18 * H, x_leg))

    # Measure foot Y range near bottom of boots
    foot_ys = [v.y for v in verts if v.z <= 0.08 * H]
    foot_front_y = min(foot_ys) if foot_ys else -0.10 * H
    foot_center_y = median(foot_ys, 0.0)

    # 2. Vertical torso proportions
    z_ankle = 0.07 * H
    z_knee = 0.27 * H if not is_bulky else 0.25 * H
    z_hip = 0.48 * H if not is_bulky else 0.45 * H
    z_waist = 0.56 * H if not is_bulky else 0.53 * H
    z_chest = 0.68 * H if not is_bulky else 0.64 * H
    z_shoulder = 0.77 * H if not is_bulky else 0.74 * H
    z_neck = 0.82 * H if not is_bulky else 0.80 * H
    z_head_top = 0.98 * H

    # 3. Measure shoulder X & arm drop angle directly from outer arm vertices (|x| > 0.23*H, z > 0.36*H)
    x_shoulder = (0.17 * H) if is_bulky else (0.125 * H)
    # Collect symmetric arm samples (abs(x), z, y) past the coat/torso width
    outer_thresh = 0.24 * H if not is_bulky else 0.28 * H
    arm_pts = [(abs(v.x), v.z, v.y) for v in verts if abs(v.x) >= outer_thresh and v.z >= 0.32 * H]
    if len(arm_pts) >= 20:
        # Take outer-most wrist/hand region (top 25% of |x| in arm_pts)
        arm_pts.sort(key=lambda p: p[0])
        hand_slice = arm_pts[int(len(arm_pts) * 0.78) :]
        x_hand = median([p[0] for p in hand_slice], max_abs_x * 0.92)
        z_hand = median([p[1] for p in hand_slice], 0.48 * H)
        y_hand = median([p[2] for p in hand_slice], 0.0)
        dx = max(x_hand - x_shoulder, 0.12 * H)
        dz = z_shoulder - z_hand
        arm_drop_rad = math.atan2(max(0.0, dz), dx)
        arm_drop_rad = max(math.radians(12.0), min(math.radians(58.0), arm_drop_rad))
        arm_len = math.hypot(dx, dz)
    else:
        arm_drop_rad = math.radians(40.0)
        arm_len = 0.34 * H
        y_hand = 0.0

    # Torso Y center at chest & hips
    chest_ys = [v.y for v in verts if 0.62 * H <= v.z <= 0.76 * H and abs(v.x) < x_shoulder]
    y_torso = median(chest_ys, 0.0)

    lm = {
        "H": H,
        "x_leg": x_leg,
        "x_shoulder": x_shoulder,
        "arm_len": arm_len,
        "arm_drop_rad": arm_drop_rad,
        "y_torso": y_torso,
        "y_hand": y_hand,
        "foot_center_y": foot_center_y,
        "foot_front_y": foot_front_y,
        "z_ankle": z_ankle,
        "z_knee": z_knee,
        "z_hip": z_hip,
        "z_waist": z_waist,
        "z_chest": z_chest,
        "z_shoulder": z_shoulder,
        "z_neck": z_neck,
        "z_head_top": z_head_top,
    }
    print(
        f"[rig] landmarks: H={H:.3f} x_leg={x_leg:.3f} x_sh={x_shoulder:.3f} "
        f"arm_len={arm_len:.3f} arm_drop={math.degrees(arm_drop_rad):.1f} deg",
        flush=True,
    )
    return lm


def build_apose_armature(lm: dict[str, Any]) -> bpy.types.Object:
    """Creates a clean 23-bone humanoid deform rig aligned inside the character's A-pose mesh."""
    arm_data = bpy.data.armatures.new("Rig")
    arm_obj = bpy.data.objects.new("Rig", arm_data)
    bpy.context.scene.collection.objects.link(arm_obj)
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.mode_set(mode="EDIT")

    H = lm["H"]
    y0 = lm["y_torso"]
    x_sh = lm["x_shoulder"]
    x_leg = lm["x_leg"]
    z_sh = lm["z_shoulder"]
    arm_len = lm["arm_len"]
    drop = lm["arm_drop_rad"]

    # Arm unit vector in A-pose (downward by `drop` from horizontal ±X)
    ux = math.cos(drop)
    uz = -math.sin(drop)
    l_upper = arm_len * 0.42
    l_lower = arm_len * 0.38
    l_wrist = arm_len * 0.08
    l_hand = arm_len * 0.14

    def arm_pt(side: float, dist: float) -> Vector:
        return Vector((side * (x_sh + dist * ux), y0, z_sh + dist * uz))

    coords: dict[str, tuple[Vector, Vector]] = {
        "root": (Vector((0.0, y0, 0.0)), Vector((0.0, y0, lm["z_hip"] * 0.55))),
        "hips": (Vector((0.0, y0, lm["z_hip"])), Vector((0.0, y0, lm["z_waist"]))),
        "spine": (Vector((0.0, y0, lm["z_waist"])), Vector((0.0, y0, lm["z_chest"]))),
        "chest": (Vector((0.0, y0, lm["z_chest"])), Vector((0.0, y0, lm["z_neck"]))),
        "head": (Vector((0.0, y0, lm["z_neck"])), Vector((0.0, y0, lm["z_head_top"]))),
    }

    for side_str, s in (("l", 1.0), ("r", -1.0)):
        p_sh = arm_pt(s, 0.0)
        p_el = arm_pt(s, l_upper)
        p_wr = arm_pt(s, l_upper + l_lower)
        p_hd = arm_pt(s, l_upper + l_lower + l_wrist)
        p_tip = arm_pt(s, l_upper + l_lower + l_wrist + l_hand)
        p_slot = p_hd.lerp(p_tip, 0.55)
        coords[f"upperarm.{side_str}"] = (p_sh, p_el)
        coords[f"lowerarm.{side_str}"] = (p_el, p_wr)
        coords[f"wrist.{side_str}"] = (p_wr, p_hd)
        coords[f"hand.{side_str}"] = (p_hd, p_tip)
        coords[f"handslot.{side_str}"] = (p_slot, p_slot + Vector((0.0, -0.10 * H, 0.0)))

        fy = lm["foot_center_y"]
        coords[f"upperleg.{side_str}"] = (
            Vector((s * x_leg, y0, lm["z_hip"])),
            Vector((s * x_leg, y0, lm["z_knee"])),
        )
        coords[f"lowerleg.{side_str}"] = (
            Vector((s * x_leg, y0, lm["z_knee"])),
            Vector((s * x_leg, fy, lm["z_ankle"])),
        )
        coords[f"foot.{side_str}"] = (
            Vector((s * x_leg, fy, lm["z_ankle"])),
            Vector((s * x_leg, min(lm["foot_front_y"] * 0.7, fy - 0.05 * H), 0.02 * H)),
        )
        coords[f"toes.{side_str}"] = (
            Vector((s * x_leg, min(lm["foot_front_y"] * 0.7, fy - 0.05 * H), 0.02 * H)),
            Vector((s * x_leg, min(lm["foot_front_y"], fy - 0.12 * H), 0.02 * H)),
        )

    ebones = arm_data.edit_bones
    for name, parent_name in DEFORM_BONE_ORDER:
        eb = ebones.new(name)
        head, tail = coords[name]
        eb.head = head
        eb.tail = tail
        eb.use_deform = not name.startswith("handslot") and name != "root"
        if parent_name is not None:
            eb.parent = ebones[parent_name]
            eb.use_connect = False

    # Align bone rolls cleanly before skinning
    for name, _ in DEFORM_BONE_ORDER:
        eb = ebones[name]
        if name in ("root", "hips", "spine", "chest", "head"):
            eb.align_roll(Vector((0.0, -1.0, 0.0)))
        elif "arm" in name or "wrist" in name or name.startswith("hand."):
            eb.align_roll(Vector((0.0, 0.0, 1.0)))
        elif name.startswith("handslot"):
            eb.align_roll(Vector((0.0, 0.0, 1.0)))
        elif "leg" in name or "foot" in name:
            eb.align_roll(Vector((0.0, 1.0, 0.0)))
        elif "toes" in name:
            eb.align_roll(Vector((0.0, 0.0, 1.0)))

    bpy.ops.object.mode_set(mode="OBJECT")
    return arm_obj


def point_to_segment_dist(p: Vector, a: Vector, b: Vector) -> float:
    ab = b - a
    denom = ab.length_squared
    if denom < 1e-8:
        return (p - a).length
    t = max(0.0, min(1.0, (p - a).dot(ab) / denom))
    proj = a + ab * t
    return (p - proj).length


def skin_mesh_to_armature(mesh_obj: bpy.types.Object, arm_obj: bpy.types.Object, lm: dict[str, Any]) -> None:
    """Applies Blender biharmonic heat-diffusion auto-skinning with guaranteed full coverage
    and anatomical cleanup so arms never grab coat tails and zero vertices hang behind."""
    bpy.ops.object.select_all(action="DESELECT")
    mesh_obj.select_set(True)
    arm_obj.select_set(True)
    bpy.context.view_layer.objects.active = arm_obj

    auto_ok = True
    try:
        bpy.ops.object.parent_set(type="ARMATURE_AUTO")
    except RuntimeError as exc:
        print(f"[rig] ARMATURE_AUTO failed ({exc}); using anatomical fallback skinning", flush=True)
        auto_ok = False
        bpy.ops.object.parent_set(type="ARMATURE_NAME")

    # Gather deform bone segments in local space
    deform_bones = [b for b in arm_obj.data.bones if b.use_deform]
    segs = [(b.name, b.head_local.copy(), b.tail_local.copy()) for b in deform_bones]
    vgroups = {vg.name: vg for vg in mesh_obj.vertex_groups}
    for b in deform_bones:
        if b.name not in vgroups:
            vgroups[b.name] = mesh_obj.vertex_groups.new(name=b.name)

    H = lm["H"]
    z_hip = lm["z_hip"]
    z_neck = lm["z_neck"]
    x_sh = lm["x_shoulder"]

    # Check how many vertices actually received weights from ARMATURE_AUTO
    unweighted: list[int] = []
    for v in mesh_obj.data.vertices:
        total = sum(g.weight for g in v.groups)
        if total < 0.05:
            unweighted.append(v.index)

    print(
        f"[rig] heat-skin check: auto_ok={auto_ok} unweighted={len(unweighted)}/{len(mesh_obj.data.vertices)}",
        flush=True,
    )

    # Also keep fallback unweighted check consistent with wide mech hands:
    if unweighted:
        for vi in unweighted:
            p = mesh_obj.data.vertices[vi].co
            scores: list[tuple[float, str]] = []
            for bname, a, b in segs:
                # Guard: never assign arm bones to inner torso/legs/coat column
                if ("arm" in bname or "wrist" in bname or "hand" in bname) and (
                    abs(p.x) < x_sh * 0.95 or (p.z < 0.56 * H and abs(p.x) < x_sh * 1.45)
                ):
                    continue
                # Guard: never cross left/right side limbs
                if bname.endswith(".l") and p.x < -0.02 * H:
                    continue
                if bname.endswith(".r") and p.x > 0.02 * H:
                    continue
                if ("leg" in bname or "foot" in bname or "toes" in bname) and p.z > z_hip + 0.08 * H:
                    continue
                d = point_to_segment_dist(p, a, b)
                scores.append((d, bname))
            scores.sort(key=lambda t: t[0])
            top = scores[:3]
            inv = [(1.0 / max(d, 0.008) ** 2.4, bn) for d, bn in top]
            s_tot = sum(w for w, _ in inv)
            for w, bn in inv:
                vgroups[bn].add([vi], w / s_tot, "REPLACE")

    # Anatomical scrub: strip stray arm/hand bleed off the coat tails & lower legs (common on long coats!)
    arm_g_indices = {
        vg.index
        for vg in mesh_obj.vertex_groups
        if any(tok in vg.name for tok in ("arm", "wrist", "hand"))
    }
    # Guard for fallback weights: allow low-hanging mech hands when clearly outside the torso/leg column
    for v in mesh_obj.data.vertices:
        p = v.co
        # Coat-tail / thigh scrub: ONLY strip arm bleed from torso/coat/leg column (`abs(p.x) < x_sh * 1.45`)!
        # Never strip outer arm/hand vertices (`abs(p.x) >= x_sh * 1.45`) even when wide mech fingers hang low!
        if p.z < 0.56 * H and abs(p.x) < x_sh * 1.45:
            has_arm = any(g.group in arm_g_indices and g.weight > 0.001 for g in v.groups)
            if has_arm:
                for vg in mesh_obj.vertex_groups:
                    if vg.index in arm_g_indices:
                        vg.remove([v.index])
                # Re-normalize remaining weights, or assign to hips/upperleg
                rem = [(g.group, g.weight) for g in v.groups if g.weight > 1e-4]
                tot = sum(w for _, w in rem)
                if tot > 0.05:
                    for gi, w in rem:
                        mesh_obj.vertex_groups[gi].add([v.index], w / tot, "REPLACE")
                else:
                    target_bone = "upperleg.l" if p.x > 0.03 * H else ("upperleg.r" if p.x < -0.03 * H else "hips")
                    vgroups[target_bone].add([v.index], 1.0, "REPLACE")

        # Keep head solid on `head` bone so facial features never squash during shoulder swings
        if p.z >= z_neck + 0.02 * H and abs(p.x) < x_sh * 0.95:
            for vg in mesh_obj.vertex_groups:
                if vg.name != "head":
                    vg.remove([v.index])
            vgroups["head"].add([v.index], 1.0, "REPLACE")

    # Gentle weight smoothing for clean cloth & shoulder bends
    bpy.ops.object.select_all(action="DESELECT")
    mesh_obj.select_set(True)
    bpy.context.view_layer.objects.active = mesh_obj
    bpy.ops.object.mode_set(mode="WEIGHT_PAINT")
    try:
        bpy.ops.object.vertex_group_smooth(group_select_mode="ALL", factor=0.35, repeat=2, expand=0.0)
        bpy.ops.object.vertex_group_normalize_all(group_select_mode="ALL", lock_active=False)
    except RuntimeError:
        pass
    bpy.ops.object.mode_set(mode="OBJECT")


def convert_apose_to_knight_tpose(
    mesh_obj: bpy.types.Object,
    arm_obj: bpy.types.Object,
    source_rest_axes: dict[str, Matrix],
    lm: dict[str, Any],
) -> None:
    """Rotates Levy's skinned A-pose arms smoothly into horizontal T-pose, bakes the new
    rest pose onto both mesh and armature, and matches every bone's local rest roll exactly
    to `Knight.glb` so all 28 animations transfer 1-to-1 with zero twist glitches."""
    drop = lm["arm_drop_rad"]

    bpy.ops.object.select_all(action="DESELECT")
    arm_obj.select_set(True)
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.mode_set(mode="POSE")

    # Raise arms from A-pose to strictly horizontal T-pose.
    # For upperarm.l (+X, z_bone = +Z, x_bone = -Y): rotating around local X by +drop lifts +Y_bone up toward +Z?
    # Compute exact world-space rotation around world Y axis so there is zero sign ambiguity!
    for side_str, sign in (("l", -1.0), ("r", 1.0)):
        pb = arm_obj.pose.bones[f"upperarm.{side_str}"]
        pb.rotation_mode = "QUATERNION"
        # World rotation lifting arm from downward angle `drop` to horizontal:
        # Left arm (+X, -Z) needs rotation around +Y by -drop:
        #   Ry(theta)*(cos d, 0, -sin d) = (cos d cos t - sin d sin t, 0, -cos d sin t - sin d cos t)
        #   Setting t = -drop gives (cos(d-d)? wait: cos d cos(-d) - sin d sin(-d) = cos^2 d + sin^2 d = 1, z = 0)!
        # Right arm (-X, -Z) needs rotation around +Y by +drop!
        world_rot = Matrix.Rotation(sign * drop, 3, "Y")
        # Convert world delta into bone local basis: R_local = B_rest^T @ world_rot @ B_rest
        b_rest = arm_obj.data.bones[f"upperarm.{side_str}"].matrix_local.to_3x3()
        local_rot = (b_rest.inverted() @ world_rot @ b_rest).to_quaternion()
        pb.rotation_quaternion = local_rot

    bpy.context.view_layer.update()
    bpy.ops.object.mode_set(mode="OBJECT")

    # Apply the Armature modifier on CharacterMesh so mesh geometry is now in clean T-pose!
    bpy.ops.object.select_all(action="DESELECT")
    mesh_obj.select_set(True)
    bpy.context.view_layer.objects.active = mesh_obj
    arm_mod = next((m for m in mesh_obj.modifiers if m.type == "ARMATURE"), None)
    if arm_mod is None:
        raise RuntimeError("Missing ARMATURE modifier before T-pose apply!")
    bpy.ops.object.modifier_apply(modifier=arm_mod.name)

    # Apply Pose as Rest Pose on Armature
    bpy.ops.object.select_all(action="DESELECT")
    arm_obj.select_set(True)
    bpy.context.view_layer.objects.active = arm_obj
    bpy.ops.object.mode_set(mode="POSE")
    bpy.ops.pose.armature_apply(selected=False)
    bpy.ops.object.mode_set(mode="OBJECT")

    # Align every Edit Bone's exact direction & roll to match Knight.glb's rest axes!
    bpy.ops.object.mode_set(mode="EDIT")
    ebones = arm_obj.data.edit_bones
    for name, _ in DEFORM_BONE_ORDER:
        if name not in source_rest_axes:
            continue
        eb = ebones[name]
        src_m = source_rest_axes[name]
        src_y = src_m.col[1].normalized()
        src_z = src_m.col[2].normalized()
        # Keep the bone's fitted head & length, snap exact orientation to Knight's rest basis!
        length = max((eb.tail - eb.head).length, 0.04)
        eb.tail = eb.head + src_y * length
        eb.align_roll(src_z)
    bpy.ops.object.mode_set(mode="OBJECT")

    # Re-add Armature modifier (all vertex groups remained intact on CharacterMesh!)
    new_mod = mesh_obj.modifiers.new(name="Armature", type="ARMATURE")
    new_mod.object = arm_obj
    mesh_obj.parent = arm_obj


def import_source_rig_and_extract_rest(source_glb: pathlib.Path) -> tuple[bpy.types.Object, dict[str, Matrix], float]:
    before_objs = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=str(source_glb.resolve()))
    new_objs = [o for o in bpy.data.objects if o not in before_objs]
    src_arm = next(o for o in new_objs if o.type == "ARMATURE")
    src_arm.name = "SourceKnightRig"

    # Hide all source meshes (we only need SourceKnightRig to evaluate its animations)
    for o in new_objs:
        if o != src_arm:
            o.hide_viewport = True
            o.hide_render = True

    rest_axes: dict[str, Matrix] = {}
    for name, _ in DEFORM_BONE_ORDER:
        if name in src_arm.data.bones:
            rest_axes[name] = src_arm.data.bones[name].matrix_local.to_3x3().copy()

    knight_hip_z = src_arm.data.bones["hips"].head_local.z
    return src_arm, rest_axes, knight_hip_z


def set_action_safe(arm: bpy.types.Object, action: bpy.types.Action) -> None:
    if arm.animation_data is None:
        arm.animation_data_create()
    arm.animation_data.use_nla = False
    arm.animation_data.action = action
    if hasattr(action, "slots") and len(action.slots) > 0:
        if getattr(arm.animation_data, "action_slot", None) is None:
            arm.animation_data.action_slot = action.slots[0]


def retarget_canonical_actions(
    src_arm: bpy.types.Object,
    dst_arm: bpy.types.Object,
    hip_scale: float,
) -> list[bpy.types.Action]:
    """Transfers all canonical Knight.glb actions to dst_arm in pose space with proportional
    hips/root translation scaling so jumps, crouches, spins, and strikes stay grounded."""
    scene = bpy.context.scene
    actions_by_lower = {a.name.lower(): a for a in bpy.data.actions}

    # Precompute rest local matrices for relative delta extraction
    src_rest_rel: dict[str, Matrix] = {}
    for name, parent_name in DEFORM_BONE_ORDER:
        b = src_arm.data.bones[name]
        if parent_name is None:
            src_rest_rel[name] = b.matrix_local.copy()
        else:
            pb = src_arm.data.bones[parent_name]
            src_rest_rel[name] = pb.matrix_local.inverted() @ b.matrix_local

    # Set quaternion mode on all destination pose bones
    for name, _ in DEFORM_BONE_ORDER:
        pb = dst_arm.pose.bones[name]
        pb.rotation_mode = "QUATERNION"

    retargeted: list[bpy.types.Action] = []
    if dst_arm.animation_data is None:
        dst_arm.animation_data_create()
    dst_arm.animation_data.use_nla = False

    for target_name in CANONICAL_ACTIONS:
        src_act = actions_by_lower.get(target_name.lower())
        if src_act is None:
            print(f"[rig] WARNING: source action '{target_name}' missing in Knight.glb", flush=True)
            continue

        start_f, end_f = src_act.frame_range
        f0 = int(math.floor(start_f))
        f1 = int(math.ceil(end_f))
        span = max(1, f1 - f0)
        # Dense sample every 1–2 frames (cap at 24 samples per clip for super fast glTF export & crisp curves)
        step = 1 if span <= 24 else max(1, span // 20)
        sample_frames = list(range(f0, f1 + 1, step))
        if sample_frames[-1] != f1:
            sample_frames.append(f1)

        # Rename source action temporarily so new action owns the exact canonical name!
        src_act.name = f"__SRC__{target_name}"
        dst_act = bpy.data.actions.new(name=target_name)
        dst_act.use_fake_user = True
        dst_arm.animation_data.action = dst_act
        if hasattr(dst_arm.animation_data, "action_slot"):
            dst_arm.animation_data.action_slot = None

        set_action_safe(src_arm, src_act)

        for frame in sample_frames:
            scene.frame_set(frame)
            bpy.context.view_layer.update()

            for name, parent_name in DEFORM_BONE_ORDER:
                src_pb = src_arm.pose.bones[name]
                dst_pb = dst_arm.pose.bones[name]

                # Exact parent-relative pose matrix on SourceRig (captures both FK and IK!)
                if parent_name is None:
                    src_rel = src_pb.matrix
                else:
                    src_rel = src_arm.pose.bones[parent_name].matrix.inverted() @ src_pb.matrix

                # Pure local basis delta relative to rest pose
                delta_m = src_rest_rel[name].inverted() @ src_rel
                delta_loc, delta_quat, _ = delta_m.decompose()
                dst_pb.rotation_quaternion = delta_quat

                if name in ("root", "hips"):
                    dst_pb.location = delta_loc * hip_scale
                    dst_pb.keyframe_insert(data_path="location", frame=frame)
                else:
                    dst_pb.location = Vector((0.0, 0.0, 0.0))
                dst_pb.keyframe_insert(data_path="rotation_quaternion", frame=frame)

        retargeted.append(dst_act)

    print(f"[rig] retargeted {len(retargeted)} canonical Smash/Mega Man/Sonic actions!", flush=True)
    return retargeted


def build_native_emission_texture(mesh_obj: bpy.types.Object, preset: str) -> None:
    """Extracts a crisp native emission texture directly from glowing accent pixels on the
    character's baked TRELLIS.2 albedo texture and connects it to Principled BSDF Emission Color
    so `bake_sprites.py` automatically captures Rift Diamond / visor / reactor HDR Bloom!"""
    for slot in mesh_obj.material_slots:
        mat = slot.material
        if mat is None or not mat.node_tree:
            continue
        nt = mat.node_tree
        bsdf = next((n for n in nt.nodes if n.type == "BSDF_PRINCIPLED"), None)
        if bsdf is None:
            continue
        base_in = bsdf.inputs.get("Base Color")
        if base_in is None or not base_in.is_linked:
            continue
        tex_node = base_in.links[0].from_node
        if tex_node.type != "TEX_IMAGE" or tex_node.image is None:
            continue

        src_img = tex_node.image
        w, h = src_img.size
        if w == 0 or h == 0:
            continue

        # Read RGBA float pixels via numpy (built into Blender's Python!)
        import numpy as np

        buf = np.empty(w * h * 4, dtype=np.float32)
        src_img.pixels.foreach_get(buf)
        px = buf.reshape((h, w, 4))
        r, g, b = px[:, :, 0], px[:, :, 1], px[:, :, 2]

        out = np.zeros_like(px)
        out[:, :, 3] = 1.0

        if preset == "levy":
            # Crisp warm-cloth-vs-cold-chrome readability lift so Levy's weathered navy coat,
            # off-white linen shirt, brass buttons, and brown leather boots pop at 96x96 pixels!
            lifted = px.copy()
            lifted[:, :, :3] = np.clip(np.power(np.clip(px[:, :, :3], 0.0, 1.0), 0.74) * 1.24, 0.0, 1.0)
            src_img.pixels.foreach_set(lifted.ravel())
            src_img.pack()

            # Glowing cyan-white Rift Diamond crystal & cyan forearm energy veins
            mask = (b > 0.36) & (g > 0.36) & ((b - r) > 0.09)
            strength = np.clip((b + g - 2.0 * r) * 2.4, 0.0, 1.0) * mask
            out[:, :, 0] = 0.25 * strength
            out[:, :, 1] = 0.96 * strength
            out[:, :, 2] = 1.00 * strength
        elif preset == "vulcanus":
            # Lift dark gunmetal rivets & steel armor slightly so Vulcanus pops off Foundry walls
            lifted = px.copy()
            lifted[:, :, :3] = np.clip(np.power(np.clip(px[:, :, :3], 0.0, 1.0), 0.78) * 1.26, 0.0, 1.0)
            src_img.pixels.foreach_set(lifted.ravel())
            src_img.pack()

            # Molten amber T-visor & blazing hexagonal Forge Diamond chest reactor
            mask = (r > 0.50) & (g > 0.18) & ((r - b) > 0.30)
            strength = np.clip((r - b - 0.22) * 2.4, 0.0, 1.0) * mask
            out[:, :, 0] = 1.00 * strength
            out[:, :, 1] = 0.58 * strength
            out[:, :, 2] = 0.10 * strength
        elif preset == "borealis":
            # Glacial-cyan optic visor, Stasis Diamond core, and crystalline frost edges
            mask = (b > 0.55) & (g > 0.50) & ((b - r) > 0.16)
            strength = np.clip((b + g * 0.7 - r * 1.4 - 0.12) * 2.2, 0.0, 1.0) * mask
            out[:, :, 0] = 0.22 * strength
            out[:, :, 1] = 0.88 * strength
            out[:, :, 2] = 1.00 * strength
        elif preset == "strider":
            # Crimson optic visor & crimson forearm blade emitters
            mask = (r > 0.50) & ((r - g) > 0.22) & ((r - b) > 0.18)
            strength = np.clip((r - g - 0.15) * 2.4, 0.0, 1.0) * mask
            out[:, :, 0] = 1.00 * strength
            out[:, :, 1] = 0.16 * strength
            out[:, :, 2] = 0.22 * strength
        elif preset == "enforcer":
            # Bright orange-amber visor slot (distinct from matte hazard yellow armor: lower G/R ratio)
            mask = (r > 0.72) & (g > 0.25) & (g < 0.62) & (b < 0.22)
            strength = np.clip((r - b - 0.45) * 2.5, 0.0, 1.0) * mask
            out[:, :, 0] = 1.00 * strength
            out[:, :, 1] = 0.50 * strength
            out[:, :, 2] = 0.08 * strength
        elif preset == "arc_weaver":
            # Electric violet visor & shoulder/chest tesla rings
            mask = (b > 0.52) & (r > 0.34) & ((b - g) > 0.14)
            strength = np.clip((b - g - 0.08) * 2.2, 0.0, 1.0) * mask
            out[:, :, 0] = 0.76 * strength
            out[:, :, 1] = 0.28 * strength
            out[:, :, 2] = 1.00 * strength
        elif preset == "phantom":
            # Subtle charcoal lift on matte-black stealth synth armor so silhouette reads cleanly
            # against dark 2085 Foundry backgrounds while neon-magenta visor & thrusters blaze!
            lifted = px.copy()
            lifted[:, :, :3] = np.clip(np.power(np.clip(px[:, :, :3], 0.0, 1.0), 0.78) * 1.26, 0.0, 1.0)
            src_img.pixels.foreach_set(lifted.ravel())
            src_img.pack()

            # Neon magenta stealth visor & shoulder/calf thrusters
            mask = (r > 0.44) & (b > 0.38) & ((r - g) > 0.18) & ((b - g) > 0.14)
            strength = np.clip(((r + b) * 0.5 - g - 0.10) * 2.6, 0.0, 1.0) * mask
            out[:, :, 0] = 1.00 * strength
            out[:, :, 1] = 0.18 * strength
            out[:, :, 2] = 0.88 * strength

        lit_count = int(np.count_nonzero(out[:, :, 0] + out[:, :, 1] + out[:, :, 2] > 0.05))
        print(f"[rig] extracted emission mask for '{preset}': {lit_count} glowing texels", flush=True)

        emis_img = bpy.data.images.new(f"{preset}_emission_tex", width=w, height=h, alpha=True)
        emis_img.pixels.foreach_set(out.ravel())
        emis_img.pack()

        emis_tex = nt.nodes.new("ShaderNodeTexImage")
        emis_tex.image = emis_img
        emis_tex.interpolation = "Closest"
        nt.links.new(emis_tex.outputs["Color"], bsdf.inputs["Emission Color"])
        bsdf.inputs["Emission Strength"].default_value = 2.4


def make_mat(name: str, base_rgb: tuple[float, float, float], emis_rgb: tuple[float, float, float] | None = None, metallic: float = 0.2, roughness: float = 0.7) -> bpy.types.Material:
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = (*base_rgb, 1.0)
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    if emis_rgb is not None:
        bsdf.inputs["Emission Color"].default_value = (*emis_rgb, 1.0)
        bsdf.inputs["Emission Strength"].default_value = 2.4
    return mat


def attach_to_bone(obj: bpy.types.Object, arm_obj: bpy.types.Object, bone_name: str) -> None:
    obj.parent = arm_obj
    obj.parent_type = "BONE"
    obj.parent_bone = bone_name
    # Position at bone head (remember Blender BONE parenting anchors object origin at bone tail by default!)
    b = arm_obj.data.bones[bone_name]
    obj.location = Vector((0.0, -b.length, 0.0))


def build_levy_gear(arm_obj: bpy.types.Object) -> None:
    """Builds Levy's signature 1700s Steel Cavalry Saber with glowing cyan Rift Plasma Edge
    on `handslot.r` + glowing Rift Diamond Crystal prism on `lowerarm.l`."""
    mat_steel = make_mat("LevySteel", (0.76, 0.82, 0.90), metallic=0.85, roughness=0.35)
    mat_brass = make_mat("LevyBrass", (0.82, 0.62, 0.22), metallic=0.85, roughness=0.38)
    mat_grip = make_mat("LevyGrip", (0.24, 0.14, 0.08), metallic=0.05, roughness=0.85)
    mat_plasma = make_mat("LevyRiftPlasma", (0.22, 0.94, 1.0), emis_rgb=(0.18, 0.95, 1.0), metallic=0.1, roughness=0.2)

    # 1. Curved 1700s Cavalry Saber (`1H_Sword`) — aligned along bone +Y (forward out of handslot.r!)
    mesh = bpy.data.meshes.new("1H_Sword")
    bm = bmesh.new()

    # Leather grip cylinder along Y in [-0.14, 0.08]
    bmesh.ops.create_cone(
        bm,
        cap_ends=True,
        segments=8,
        radius1=0.032,
        radius2=0.032,
        depth=0.22,
        matrix=Matrix.Translation((0.0, -0.03, 0.0)) @ Matrix.Rotation(math.radians(90.0), 4, "X"),
    )
    for f in bm.faces:
        f.material_index = 2

    # Brass handguard / pommel + D-guard bar
    prev = set(bm.faces)
    bmesh.ops.create_cube(bm, size=1.0, matrix=Matrix.Translation((0.0, 0.09, 0.0)) @ Matrix.Diagonal((0.08, 0.035, 0.19, 1.0)))
    bmesh.ops.create_cube(bm, size=1.0, matrix=Matrix.Translation((0.0, -0.02, -0.095)) @ Matrix.Diagonal((0.03, 0.23, 0.028, 1.0)))
    bmesh.ops.create_uvsphere(bm, u_segments=8, v_segments=6, radius=0.042, matrix=Matrix.Translation((0.0, -0.15, 0.0)))
    for f in set(bm.faces) - prev:
        f.material_index = 1

    # Tapered, slightly curved 1700s steel saber spine (material 0 = steel)
    prev = set(bm.faces)
    n_segs = 8
    length = 0.96
    rings: list[list[Any]] = []
    for i in range(n_segs + 1):
        t = i / n_segs
        y = 0.11 + t * length
        # Subtle cavalry saber upward curve along +Z
        z_curve = 0.085 * (t * t)
        half_w = 0.032 * (1.0 - 0.50 * t)
        thick_top = 0.072 * (1.0 - 0.56 * t)
        thick_bot = 0.018 * (1.0 - 0.62 * t)
        if i == n_segs:
            v_tip = bm.verts.new((0.0, y + 0.09, z_curve + 0.02))
            rings.append([v_tip])
        else:
            r = [
                bm.verts.new((-half_w, y, z_curve + thick_top)),
                bm.verts.new((half_w, y, z_curve + thick_top)),
                bm.verts.new((half_w, y, z_curve - thick_bot)),
                bm.verts.new((-half_w, y, z_curve - thick_bot)),
            ]
            rings.append(r)
    for i in range(n_segs):
        r0, r1 = rings[i], rings[i + 1]
        if len(r1) == 1:
            tip = r1[0]
            for k in range(4):
                bm.faces.new((r0[k], r0[(k + 1) % 4], tip))
        else:
            for k in range(4):
                bm.faces.new((r0[k], r0[(k + 1) % 4], r1[(k + 1) % 4], r1[k]))
    for f in set(bm.faces) - prev:
        f.material_index = 0

    # Bold glowing Cyan Rift Plasma cutting edge (material 3 = emissive cyan, crisp at 96x96!)
    prev = set(bm.faces)
    e_rings: list[list[Any]] = []
    for i in range(n_segs + 1):
        t = i / n_segs
        y = 0.13 + t * (length * 0.99)
        z_curve = 0.085 * (t * t)
        edge_top = z_curve + 0.004 * (1.0 - 0.4 * t)
        edge_bot = z_curve - (0.096 * (1.0 - 0.42 * t))
        hw = 0.030 * (1.0 - 0.44 * t)
        if i == n_segs:
            e_rings.append([bm.verts.new((0.0, y + 0.10, z_curve + 0.015))])
        else:
            e_rings.append([
                bm.verts.new((-hw, y, edge_top)),
                bm.verts.new((hw, y, edge_top)),
                bm.verts.new((0.0, y, edge_bot)),
            ])
    for i in range(n_segs):
        r0, r1 = e_rings[i], e_rings[i + 1]
        if len(r1) == 1:
            tip = r1[0]
            for k in range(3):
                bm.faces.new((r0[k], r0[(k + 1) % 3], tip))
        else:
            for k in range(3):
                bm.faces.new((r0[k], r0[(k + 1) % 3], r1[(k + 1) % 3], r1[k]))
    for f in set(bm.faces) - prev:
        f.material_index = 3

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(mesh)
    bm.free()

    mesh.materials.append(mat_steel)
    mesh.materials.append(mat_brass)
    mesh.materials.append(mat_grip)
    mesh.materials.append(mat_plasma)

    saber_obj = bpy.data.objects.new("1H_Sword", mesh)
    bpy.context.scene.collection.objects.link(saber_obj)
    attach_to_bone(saber_obj, arm_obj, "handslot.r")
    # Note: Levy's sculpted Rift Diamond crystal & glowing cyan forearm veins are already
    # captured natively on the TRELLIS.2 mesh & extracted directly into the emission map!


