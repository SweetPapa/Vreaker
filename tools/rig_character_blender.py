def cleanup_source_rig(src_arm: bpy.types.Object) -> None:
    """Removes the temporary SourceKnightRig, its hidden meshes, and its `__SRC__` actions."""
    for obj in list(bpy.data.objects):
        if obj == src_arm or obj.parent == src_arm or obj.hide_render:
            bpy.data.objects.remove(obj, do_unlink=True)
    for act in list(bpy.data.actions):
        if act.name.startswith("__SRC__") or act.name not in CANONICAL_ACTIONS:
            bpy.data.actions.remove(act, do_unlink=True)


def render_verification_previews(arm_obj: bpy.types.Object, preview_dir: pathlib.Path) -> None:
    """Renders crisp side-view & front-view pose checks of key animations for visual inspection."""
    preview_dir.mkdir(parents=True, exist_ok=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x = 384
    scene.render.resolution_y = 384
    scene.render.film_transparent = False
    scene.eevee.taa_render_samples = 4

    world = bpy.data.worlds.new("PrevWorld")
    scene.world = world
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs["Color"].default_value = (0.12, 0.15, 0.22, 1.0)
    world.node_tree.nodes["Background"].inputs["Strength"].default_value = 0.85

    sun = bpy.data.lights.new("PrevSun", "SUN")
    sun.energy = 2.8
    sun_obj = bpy.data.objects.new("PrevSun", sun)
    sun_obj.rotation_euler = (math.radians(48), math.radians(-18), math.radians(-22))
    scene.collection.objects.link(sun_obj)

    cam = bpy.data.cameras.new("PrevCam")
    cam.type = "ORTHO"
    cam.ortho_scale = 3.2
    cam_obj = bpy.data.objects.new("PrevCam", cam)
    scene.collection.objects.link(cam_obj)
    scene.camera = cam_obj

    # Rotate rig temporarily so character faces +X right (same as sprite baker)
    orig_z = arm_obj.rotation_euler.z
    arm_obj.rotation_euler.z = math.radians(90.0)
    cam_obj.location = (0.1, -8.0, 1.35)
    cam_obj.rotation_euler = (math.radians(90.0), 0.0, 0.0)

    checks = [
        ("idle", "Idle", 0.0),
        ("run", "Running_A", 0.35),
        ("jab", "1H_Melee_Attack_Slice_Horizontal", 0.45),
        ("f_smash", "2H_Melee_Attack_Slice", 0.50),
        ("spin", "2H_Melee_Attack_Spinning", 0.35),
        ("buster", "1H_Ranged_Shoot", 0.50),
    ]
    for tag, act_name, frac in checks:
        act = bpy.data.actions.get(act_name)
        if act is None:
            continue
        set_action_safe(arm_obj, act)
        f0, f1 = act.frame_range
        f = f0 + (f1 - f0) * frac
        scene.frame_set(int(math.floor(f)), subframe=f - math.floor(f))
        bpy.context.view_layer.update()
        scene.render.filepath = str(preview_dir / f"pose_{tag}.png")
        bpy.ops.render.render(write_still=True)

    # Restore rig rotation and clean up temporary preview light/camera
    arm_obj.rotation_euler.z = orig_z
    bpy.data.objects.remove(cam_obj, do_unlink=True)
    bpy.data.objects.remove(sun_obj, do_unlink=True)


def export_rigged_glb(arm_obj: bpy.types.Object, out_path: pathlib.Path) -> None:
    # Ensure Idle is active on export and every action is retained cleanly
    idle = bpy.data.actions.get("Idle")
    if idle is not None:
        set_action_safe(arm_obj, idle)
    bpy.context.scene.frame_set(0)
    bpy.context.view_layer.update()

    out_path.parent.mkdir(parents=True, exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=str(out_path.resolve()),
        export_format="GLB",
        export_animations=True,
        export_animation_mode="ACTIONS",
        export_bake_animation=False,
        export_skins=True,
        export_materials="EXPORT",
        export_image_format="AUTO",
    )
    print(f"[rig] exported rigged GLB -> {out_path} ({out_path.stat().st_size:,} bytes)", flush=True)


