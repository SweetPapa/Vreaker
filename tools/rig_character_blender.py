#!/usr/bin/env python3
"""Headless Blender 5.2 Auto-Rigger, Animation Retargeter & Weapon/Emission Builder
for *VELOCITY // BREAKER*.

Takes a static A-pose `.glb` generated by WARLOCK TRELLIS.2 (or Hunyuan3D), automatically:
  1. Normalizes scale, ground contact (`Z = 0`), and orientation (`-Y` forward, `+Z` up).
  2. Analyzes the mesh's actual 3D silhouette landmarks (head, shoulders, elbows, wrists,
     hips, knees, ankles, arm drop angle).
  3. Builds a 23-bone humanoid deform rig matching `Knight.glb`'s exact bone names & axes.
  4. Skins the mesh with Blender biharmonic heat-diffusion (`ARMATURE_AUTO`) + anatomical
     fallback weights so zero vertices are ever left unweighted or cross-bound.
  5. Converts the skinned mesh cleanly from A-pose to T-pose rest alignment matching
     `Knight.glb`'s exact bone orientations & rolls.
  6. Retargets all 28 *VELOCITY // BREAKER* Smash/Mega Man/Sonic animations directly from
     `Knight.glb` with proportional hip/root height scaling so feet stay planted cleanly.
  7. Extracts a crisp native emission texture from glowing accents on the character's
     baked texture (Rift cyan gauntlet, Vulcanus molten visor & Forge Diamond, etc.) AND
     attaches bespoke 3D Story-Bible weapons with emissive plasma edges to `handslot.r/l`.
  8. Exports a clean, bake-ready `.glb` compatible with `tools/sprite_baker/bake_sprites.py`.

Usage:
    blender --background --python tools/rig_character_blender.py -- \
        --input raw_assets/characters/levy_raw.glb \
        --out raw_assets/characters/levy_rigged.glb \
        --preset levy \
        --preview-dir /tmp/levy_rig_preview
"""

