    args = parse_args()
    clear_scene()

    target_h = args.height if args.height is not None else preset_height(args.preset)
    char_mesh = import_and_merge_character_mesh(args.input, target_h, args.yaw_deg)
    lm = measure_character_landmarks(char_mesh, args.preset)

    src_arm, src_rest_axes, knight_hip_z = import_source_rig_and_extract_rest(args.source_rig)
    arm_obj = build_apose_armature(lm)
